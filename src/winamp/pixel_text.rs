use cranpose_ui::ImageBitmap;
pub fn render(text: &str, width: u32, height: u32, color: [u8; 4]) -> Option<ImageBitmap> {
    if !text.is_ascii() || width == 0 || height == 0 {
        return None;
    }
    let mut pixels = vec![0; width as usize * height as usize * 4];
    let top = height.saturating_sub(7) / 2;
    for (index, ch) in text.chars().enumerate() {
        let rows = glyph(ch)?;
        let left = index as u32 * 6;
        if left >= width {
            break;
        }
        for (y, bits) in rows.into_iter().enumerate() {
            for x in 0..5 {
                if bits & (1 << (4 - x)) != 0 && left + x < width && top + (y as u32) < height {
                    let at = (((top + y as u32) * width + left + x) * 4) as usize;
                    pixels[at..at + 4].copy_from_slice(&color);
                }
            }
        }
    }
    ImageBitmap::from_rgba8(width, height, pixels).ok()
}
