#[cfg(not(target_os = "ios"))]
pub(crate) fn layout(
    text: &str,
    small: bool,
    scale: i32,
    spacing: i32,
    mut emit: impl FnMut(i32, i32),
) -> Vec<char> {
    let cell = if small { 4 } else { 5 };
    let mut skipped: Vec<char> = Vec::new();
    let mut pen = 0;
    for ch in text.chars() {
        if ch == ' ' {
            pen += (cell + spacing) * scale;
            continue;
        }
        let rows = if small {
            small_glyph(ch).map(Vec::from)
        } else {
            glyph(ch).map(Vec::from)
        };
        let Some(rows) = rows else {
            if !skipped.contains(&ch) {
                skipped.push(ch);
            }
            pen += (cell + spacing) * scale;
            continue;
        };
        for (row, bits) in rows.iter().enumerate() {
            for column in 0..cell {
                if bits & (1 << (cell - 1 - column)) == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        emit(pen + column * scale + dx, row as i32 * scale + dy);
                    }
                }
            }
        }
        pen += (cell + spacing) * scale;
    }
    skipped
}
#[cfg(not(target_os = "ios"))]
pub(crate) fn measure(text: &str, small: bool, scale: i32, spacing: i32) -> TextExtent {
    let cell = if small { 4 } else { 5 };
    let (mut right, mut bottom) = (0, 0);
    let missing = layout(text, small, scale, spacing, |dx, dy| {
        right = right.max(dx + 1);
        bottom = bottom.max(dy + 1);
    });
    TextExtent {
        width: right,
        height: bottom,
        advance: text.chars().count() as i32 * (cell + spacing) * scale,
        missing,
    }
}
#[cfg(not(target_os = "ios"))]
pub(crate) struct TextExtent {
    pub width: i32,
    pub height: i32,
    pub advance: i32,
    pub missing: Vec<char>,
}
